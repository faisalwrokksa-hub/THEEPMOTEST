#!/usr/bin/env bash
# Phase 16B: RESTORE a verified backup into an isolated temporary staging DB.
# Never operates on the source database, and cannot run against production.
# Usage on the staging host from the project directory:
#   infra/rehearse-db-restore.sh staging /absolute/path/epmo-staging-....dump
set -euo pipefail
umask 077

if [[ "${1:-}" != staging || $# -ne 2 ]]; then
  echo 'BLOCKED: staging-only usage: infra/rehearse-db-restore.sh staging /absolute/path/epmo-staging-....dump' >&2
  exit 2
fi
backup=$2
if [[ "$backup" != /* || -L "$backup" || ! "$backup" =~ ^/[a-zA-Z0-9_./-]+$ ||
      "$backup" == *'/../'* || "$backup" == *'/..' || ! -f "$backup" ]]; then
  echo 'BLOCKED: backup must be an existing safe, regular, absolute non-symlink file' >&2
  exit 2
fi
if [[ ! "$(basename -- "$backup")" =~ ^epmo-staging-[0-9]{8}T[0-9]{6}Z-[a-zA-Z0-9]+\.dump$ ]]; then
  echo 'BLOCKED: not a staging backup generated by the EPMO backup command' >&2
  exit 2
fi
if [[ ! -r .env.staging ]]; then
  echo 'BLOCKED: .env.staging not found; do not run against production' >&2
  exit 2
fi
set -a
# shellcheck disable=SC1091
. ./.env.staging
set +a
if [[ "${DEPLOYMENT_ENV:-}" != staging ]]; then
  echo 'BLOCKED: DEPLOYMENT_ENV must explicitly be staging' >&2
  exit 2
fi
PG_USER=${PG_USER:-}
PG_DB=${PG_DB:-pmo}
if [[ ! "$PG_USER" =~ ^[a-zA-Z_][a-zA-Z0-9_]*$ ||
      ! "$PG_DB" =~ ^[a-zA-Z_][a-zA-Z0-9_]*$ ]]; then
  echo 'BLOCKED: invalid PG_USER or PG_DB identifier' >&2
  exit 2
fi
if [[ ! -r "$backup.sha256" || -L "$backup.sha256" ]]; then
  echo 'BLOCKED: missing or unsafe backup checksum sidecar' >&2
  exit 2
fi
# Accept only a single sha256sum entry for THIS named archive. A forged
# sidecar must not be able to point the check at some different file.
backup_dir=$(dirname -- "$backup")
expected_name=$(basename -- "$backup")
sidecar_line=$(cat -- "$backup.sha256")
if [[ ! "$sidecar_line" =~ ^[0-9a-f]{64}[[:space:]][[:space:]] ]] ||
    [[ "${sidecar_line:66}" != "$expected_name" ]]; then
  echo 'BLOCKED: backup checksum sidecar does not name the requested archive' >&2
  exit 1
fi
if ! (cd "$backup_dir" && sha256sum -c -- "$expected_name.sha256" >/dev/null); then
  echo 'BLOCKED: backup checksum verification failed' >&2
  exit 1
fi
command -v node >/dev/null || { echo 'BLOCKED: Node.js required for unpredictable temporary database name' >&2; exit 1; }
command -v docker >/dev/null || { echo 'BLOCKED: Docker required for PostgreSQL restore rehearsal' >&2; exit 1; }
restore_db="epmo_restore_$(node -e "process.stdout.write(require('node:crypto').randomBytes(8).toString('hex'))")"
dc() { docker compose -f docker-compose.prod.yml -p pmo-staging --env-file .env.staging "$@"; }
# A first deployment has no EPMO schema yet. Its pre-migration backup should
# restore to the same empty state, not be rejected for lacking tables which
# bootstrap-db.sh has not created. Existing installations MUST restore all
# three essentials. Any partial state is suspicious and blocks deployment.
# Compare SOURCE and RESTORED schema state, not just an unqualified "tables
# exist" assertion: a wrongly selected backup must not pass as a clean start.
schema_state() {
  local database="$1"
  dc exec -T postgres psql -X -tA -v ON_ERROR_STOP=1 -U "$PG_USER" -d "$database" \
    -c "SELECT
      (CASE WHEN to_regclass('public.tenants') IS NULL THEN '0' ELSE '1' END) ||
      (CASE WHEN to_regclass('public.memberships') IS NULL THEN '0' ELSE '1' END) ||
      (CASE WHEN to_regclass('public.schema_migrations') IS NULL THEN '0' ELSE '1' END)" </dev/null | tr -d '[:space:]'
}
if ! source_state=$(schema_state "$PG_DB"); then
  echo 'BLOCKED: could not inspect the source staging database' >&2
  exit 1
fi
case "$source_state" in
  000) echo 'INFO: first-time staging bootstrap; backup must restore an empty application schema' ;;
  111) echo 'INFO: existing staging database; backup must restore the full application schema' ;;
  *) echo 'BLOCKED: source staging database is partially initialized; restore rehearsal cannot approve it' >&2; exit 1 ;;
esac

created=0
cleanup() {
  if [[ "$created" == 1 ]]; then
    if ! dc exec -T postgres dropdb --if-exists -U "$PG_USER" -- "$restore_db"; then
      echo "BLOCKED: failed to remove temporary restore database $restore_db. Manual cleanup required." >&2
      exit 1
    fi
  fi
}
trap cleanup EXIT

# createdb fails if a database by that name already exists. Never drop one we
# did not create; the cleanup flag is only set after success.
if ! dc exec -T postgres createdb -U "$PG_USER" -- "$restore_db"; then
  echo 'BLOCKED: could not create isolated staging restore database' >&2
  exit 1
fi
created=1
if ! dc exec -T postgres pg_restore --exit-on-error --single-transaction \
    --no-owner --no-acl -U "$PG_USER" --dbname="$restore_db" < "$backup"; then
  echo 'BLOCKED: restoring backup into isolated staging database failed' >&2
  exit 1
fi
# The DB name is generated from cryptographic random bytes, never from input.
# Check that the restored archive has the same essential schema state as the
# SOURCE database observed before the restore. Partial restores always fail.
if ! restored_state=$(schema_state "$restore_db"); then
  echo 'BLOCKED: could not inspect the restored staging database' >&2
  exit 1
fi
if [[ "$restored_state" != "$source_state" ]]; then
  echo "BLOCKED: restored schema state does not match the source ($source_state versus $restored_state)" >&2
  exit 1
fi
printf 'PASS: verified isolated PostgreSQL restore (%s schema; temporary database will be removed)\n' \
  "$( [[ "$source_state" == '000' ]] && echo fresh || echo existing )"
