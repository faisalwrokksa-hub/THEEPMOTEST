import { Injectable, Logger, BadRequestException, NotFoundException } from '@nestjs/common';
import { BedrockRuntimeClient, ConverseCommand } from '@aws-sdk/client-bedrock-runtime';
import { sql } from 'drizzle-orm';
import { withTenant } from '@pmo/db';
import { randomUUID } from 'node:crypto';
import { currentContext } from '../tenancy/tenant-context';
import { requireCapability } from '../common/require-capability';
import { gather, digest, type Grounding } from './grounding';

const rows = (r: unknown) => r as unknown as any[];

/**
 * The instruction that keeps the assistant honest.
 *
 * Two rules do the real work. It may only use the supplied data, and it must
 * say when the data does not answer the question. A governance assistant that
 * guesses is worse than none at all: the guess gets repeated to a board by
 * someone who had no reason to doubt it, and the platform's whole claim is
 * that figures can be traced to a record.
 */
const SYSTEM = `You are Ask X, the assistant inside The EPMO, a project governance platform.

You answer questions about ONE workspace's portfolio, using ONLY the JSON facts supplied in the user message. Those facts are the complete, current state of that workspace.

Rules, in order of importance:
1. Never state a number, name, date or status that is not in the supplied facts. Do not estimate, extrapolate or fill gaps from general knowledge.
2. If the facts do not answer the question, say so plainly and name what would be needed. Do not apologise at length.
3. Name the specific records behind what you say — project codes, gate names, register item titles, people. A claim with no record behind it is the thing this platform exists to prevent.
4. Write prose for a director. Never paste JSON, braces or raw data structures, and never name a field ("the overBudget field", "drawnPct"). Say what it means instead: "none of the three projects has spent more than its budget". Refer to records the way a person would — "the open dependency on ANR, 'Contractor has not submitted signed bonds', owned by Fatima Al-Zahrani".
5. Lead with the answer. A director asked a question; give it in the first sentence, then the evidence.
6. Be concise: a few short paragraphs at most. No preamble, no restating the question, no "based on the data provided".

Do no arithmetic and no cross-record comparison. Every comparison you might need is already computed per project: drawnPct, overBudget, forecastOverBudget, varianceToBudget, mayPass. Read those rather than working them out — and never take a figure from one project's record when discussing another.

On governance: a gate passes only when every criterion is met with evidence, every approval is signed, and no open register item points at it. "mayPass" already encodes all three. A blocked gate holds the funding behind it — that is why it matters.

Money is in SAR. Write large figures readably (680M, 2.3B).

Language: answer in English. The ONLY exception is a question written in Arabic, or one that explicitly asks for Arabic — then answer entirely in Arabic. Never use any other language.`;

export type Answer = {
  threadId: string;
  question: string;
  answer: string;
  model: string;
  grounding: ReturnType<typeof digest>;
};

@Injectable()
export class AskXService {
  private readonly log = new Logger('AskX');
  private readonly region = (process.env.BEDROCK_REGION ?? process.env.AWS_REGION ?? 'ap-south-1').trim();
  /**
   * Configurable because model access in Bedrock is granted per account and
   * per model: the newer Claude models need one enablement in the console, and
   * until that happens the older one is what actually answers. An env var
   * means that upgrade is a restart, not a release.
   */
  private readonly modelId = (process.env.BEDROCK_MODEL_ID ?? 'amazon.nova-pro-v1:0').trim();
  private readonly enabled = (process.env.ASKX_ENABLED ?? 'true').trim().toLowerCase() !== 'false';
  private client: BedrockRuntimeClient | null = null;

  get status() {
    return {
      enabled: this.enabled,
      model: this.modelId,
      region: this.region,
      note: this.enabled
        ? `Answers are generated by ${this.modelId} in ${this.region}, grounded in this workspace's data only.`
        : 'Ask X is switched off for this deployment (ASKX_ENABLED=false).',
    };
  }

  private bedrock() {
    if (!this.client) this.client = new BedrockRuntimeClient({ region: this.region });
    return this.client;
  }

  /** The thread so far, so a follow-up question knows what "it" refers to. */
  private async history(tx: any, threadId: string, userId: string) {
    return rows(await tx.execute(sql`
      SELECT role, content FROM ask_messages
      WHERE thread_id = ${threadId} AND user_id = ${userId}
      ORDER BY created_at LIMIT 20`));
  }

  async ask(question: string, threadId: string | undefined, lang: 'en' | 'ar',
            path?: string): Promise<Answer> {
    // All grounding, historical messages, and stored replies can include costs.
    requireCapability('pmoa_view_financials');
    const q = question.trim();
    if (!q) throw new BadRequestException('Ask a question.');
    if (q.length > 2000) throw new BadRequestException('That question is too long — keep it under 2000 characters.');
    if (!this.enabled) throw new BadRequestException('Ask X is switched off for this deployment.');
    if (threadId && !/^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}$/i.test(threadId))
      throw new BadRequestException('Invalid conversation reference');

    const { tenantId, userId } = currentContext();
    const facts = await gather(tenantId);
    const thread = threadId || randomUUID();

    const prior = await withTenant(tenantId, (tx) => this.history(tx, thread, userId));
    // A caller must not attach its own messages to another person's thread.
    if (threadId && prior.length === 0) throw new NotFoundException('Conversation not found');

    /*
     * Converse rather than InvokeModel: one request shape for every provider,
     * so the model is a configuration value instead of a code change. That
     * matters here because the account cannot reach Anthropic models until an
     * access form is approved, and a governance assistant that cannot answer
     * at all is worse than one answering on a different model.
     */
    const messages = [
      ...prior.map((m) => ({
        role: (m.role === 'assistant' ? 'assistant' : 'user') as 'assistant' | 'user',
        content: [{ text: m.content }],
      })),
      {
        role: 'user' as const,
        content: [{
          text:
            `Facts for workspace "${facts.workspace}" as at ${facts.asOf}:\n\n` +
            '```json\n' + JSON.stringify(facts) + '\n```\n\n' +
            // Where the reader is standing, so "this project" has a referent.
            (path ? `The reader is currently on the page: ${path}\n` : '') +
            `Question${lang === 'ar' ? ' (answer in Arabic)' : ''}: ${q}`,
        }],
      },
    ];

    let answer: string;
    try {
      const res = await this.bedrock().send(new ConverseCommand({
        modelId: this.modelId,
        system: [{ text: SYSTEM }],
        messages,
        inferenceConfig: {
          maxTokens: 1400,
          temperature: 0.2,          // a governance answer should be reproducible
        },
      }));
      answer = res.output?.message?.content?.[0]?.text?.trim() || 'No answer was returned.';
    } catch (e) {
      const err = e as { name?: string; message?: string };
      // Never put provider messages into logs; they may echo prompts or customer data.
      this.log.error('Bedrock request failed; check provider telemetry using the request time.');
      // Say which kind of failure it is: "not enabled in the console" and
      // "the service is down" need different people to do different things.
      const hint = err.name === 'AccessDeniedException'
        ? ` Model access for "${this.modelId}" has not been granted in the Bedrock console for this account.`
        : err.name === 'ResourceNotFoundException'
          // Anthropic models on Bedrock need a one-time use-case form approved
          // per account. Naming that is the difference between a five-minute
          // fix and an afternoon.
          ? ` "${this.modelId}" is not available to this account — an Anthropic model needs its use-case form submitted in the Bedrock console.`
          : err.name === 'ValidationException'
            ? ` "${this.modelId}" may need an inference profile in ${this.region} rather than a bare model id.`
            : '';
      throw new BadRequestException(`Ask X could not reach the model.${hint}`);
    }

    await withTenant(tenantId, async (tx) => {
      await tx.execute(sql`
        INSERT INTO ask_messages (tenant_id, thread_id, user_id, role, content, lang)
        VALUES (${tenantId}, ${thread}, ${userId}, 'user', ${q}, ${lang})`);
      await tx.execute(sql`
        INSERT INTO ask_messages (tenant_id, thread_id, user_id, role, content, lang, model, grounding)
        VALUES (${tenantId}, ${thread}, ${userId}, 'assistant', ${answer}, ${lang},
                ${this.modelId}, ${JSON.stringify(digest(facts))}::jsonb)`);
    });

    return { threadId: thread, question: q, answer, model: this.modelId, grounding: digest(facts) };
  }

  /** One conversation, oldest first. */
  async thread(threadId: string) {
    requireCapability('pmoa_view_financials');
    const { tenantId, userId } = currentContext();
    const messages = await withTenant(tenantId, async (tx) => rows(await tx.execute(sql`
      SELECT id, role, content, lang, model, created_at AS "createdAt"
      FROM ask_messages WHERE thread_id = ${threadId} AND user_id = ${userId}
      ORDER BY created_at`)));
    if (!messages.length) throw new NotFoundException('Conversation not found');
    return messages;
  }

  /** Recent conversations, newest first, one row each. */
  async threads() {
    requireCapability('pmoa_view_financials');
    const { tenantId, userId } = currentContext();
    return withTenant(tenantId, async (tx) => rows(await tx.execute(sql`
      SELECT DISTINCT ON (thread_id) thread_id AS "threadId", content AS "opening",
             created_at AS "createdAt"
      FROM ask_messages WHERE role = 'user' AND user_id = ${userId}
      ORDER BY thread_id, created_at
    `)).sort((a, b) => String(b.createdAt).localeCompare(String(a.createdAt))).slice(0, 20));
  }

  /** What the facts currently look like — useful for showing what it can see. */
  async facts(): Promise<Grounding> {
    requireCapability('pmoa_view_financials');
    return gather(currentContext().tenantId);
  }
}
